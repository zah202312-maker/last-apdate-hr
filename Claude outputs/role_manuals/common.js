// ---------- small helpers ----------
const p = (t, c = '') => `<span class="pill${c ? ' ' + c : ''}">${t}</span>`;
const lead = (t) => `<p class="lead">${t}</p>`;
const h4 = (t) => `<h4>${t}</h4>`;
const para = (t) => `<p>${t}</p>`;
const ul = (a) => `<ul>${a.map((x) => `<li>${x}</li>`).join('')}</ul>`;
const steps = (a) => `<ol class="steps">${a.map((x) => `<li>${x}</li>`).join('')}</ol>`;
const note = (cls, h, body) => `<div class="note ${cls}"><div class="h">${h}</div>${Array.isArray(body) ? `<ul style="margin:0">${body.map((x) => `<li>${x}</li>`).join('')}</ul>` : body}</div>`;
const tip = (h, b) => note('tip', h, b);
const warn = (h, b) => note('warn', h, b);
const rule = (h, b) => note('rule', h, b);
const lock = (h, b) => note('lock', h, b);
const table = (heads, rows, widths = []) =>
  `<table><tr>${heads.map((h, i) => `<th${widths[i] ? ` style="width:${widths[i]}"` : ''}>${h}</th>`).join('')}</tr>${rows
    .map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join('')}</tr>`)
    .join('')}</table>`;
const cards = (a) => `<div class="grid2">${a.map(([t, d]) => `<div class="card"><div class="t">${t}</div><div class="d">${d}</div></div>`).join('')}</div>`;
const features = (a) =>
  `<div class="feature-grid">${a.map(([t, d], i) => `<div class="feature"><span class="ic">${i + 1}</span><span class="t">${t}</span><p>${d}</p></div>`).join('')}</div>`;
const flow = (a) =>
  `<div class="flow">${a.map((x) => (x.startsWith('*') ? `<span class="s a">${x.slice(1)}</span>` : `<span class="s">${x}</span>`)).join('<span class="ar">←</span>')}</div>`;

// ---------- document ----------
/**
 * doc: { file, title, footer, sub, desc, chapters: [{key,k,title,desc,body}], groups: [{title, pages:[{key,title,where,pills,body}]}],
 *        appendices: [{key,k,title,desc,body}] }
 * Page and chapter bodies may be functions of ref(key) -> page number, so text can point at other pages.
 */
function build(doc) {
  const nums = {};
  let n = 0;
  for (const g of doc.groups) for (const pg of g.pages) nums[pg.key] = ++n;
  const ref = (k) => {
    if (!(k in nums)) throw new Error('unknown page ' + k);
    return nums[k];
  };
  const body = (b) => (typeof b === 'function' ? b(ref) : b);

  const chapter = (c) =>
    `<section class="break" id="${c.key}"><div class="chapter-head"><div class="k">${c.k}</div><h2>${c.title}</h2><p>${c.desc}</p></div>${body(c.body)}</section>`;
  const page = (pg) =>
    `<section class="break" id="${pg.key}"><div class="screen-head"><div class="num">${nums[pg.key]}</div><div><h3>${pg.title}</h3><div class="where">${pg.where}${
      pg.pills ? ' ' + pg.pills : ''
    }</div></div></div>${body(pg.body)}</section>`;

  const tocLink = (key, k, label) => `<a href="#${key}"><span class="n">${k}</span>${label}</a>`;
  const toc = `<section class="break">
  <div class="chapter-head"><div class="k">المحتويات</div><h2>فهرس الدليل</h2><p>كل صفحة من النظام مرقّمة بالترتيب نفسه الذي تظهر به في قائمتك الجانبية.</p></div>
  <div class="toc">
    <div class="grp"><div class="gt">البداية</div>${doc.chapters.map((c) => tocLink(c.key, c.k, c.title)).join('')}</div>
    ${doc.groups.map((g) => `<div class="grp"><div class="gt">${g.title}</div>${g.pages.map((pg) => tocLink(pg.key, nums[pg.key], pg.title)).join('')}</div>`).join('\n    ')}
    <div class="grp"><div class="gt">ملاحق</div>${doc.appendices.map((c) => tocLink(c.key, c.k, c.title)).join('')}</div>
  </div>
</section>`;

  const style = css.replace('content:"دليل مستخدم الموارد البشرية"', `content:"${doc.footer}"`);
  const html = `<!doctype html>
<html lang="ar" dir="rtl">
<head>
<meta charset="utf-8">
<title>${doc.title}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Cairo:wght@400;600;700;800&display=swap" rel="stylesheet">
${style}
</head>
<body>
<section class="cover">
  ${coverSvg}
  <div class="inner">
    <div class="logo">HR</div>
    <div class="chip">نظام إدارة الموارد البشرية</div>
    <h1>${doc.title}</h1>
    <div class="sub">${doc.sub}</div>
    <p class="desc">${doc.desc}</p>
  </div>
  <div class="foot"><span>الإصدار 1.0</span><span>تشرين الثاني 2026</span></div>
</section>
${toc}
${doc.chapters.map(chapter).join('\n')}
${doc.groups.map((g) => g.pages.map(page).join('\n')).join('\n')}
${doc.appendices.map(chapter).join('\n')}
<p class="small" style="margin-top:14px;text-align:center">— نهاية الدليل —</p>
</body>
</html>`;
  fs.writeFileSync(path.join(__dirname, doc.file), html, 'utf8');
  return { file: doc.file, pages: n };
}

